"""Inspect this task's trusted checkpoint without loading its model tensors."""

import hashlib
import json
import pickle
import struct
from collections import Counter
from pathlib import Path
from typing import Any

import torch

import hyper_parallel
from hyper_parallel.core.distributed_checkpoint.filesystem_storage import FileSystemReader


CHECKPOINT = Path("/checkpoint")


def summarize(value: Any) -> Any:
    """Keep small counters while representing RNG tensors by shape and digest."""
    if isinstance(value, torch.Tensor):
        return {
            "type": "tensor",
            "dtype": str(value.dtype),
            "shape": list(value.shape),
            "sha256": hashlib.sha256(value.contiguous().numpy().tobytes()).hexdigest(),
        }
    if isinstance(value, dict):
        return {str(key): summarize(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        if len(value) > 64:
            return {"type": type(value).__name__, "length": len(value),
                    "pickle_sha256": hashlib.sha256(pickle.dumps(value)).hexdigest()}
        return [summarize(item) for item in value]
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    raise TypeError(f"Unsupported checkpoint metadata value: {type(value).__name__}")


def main() -> None:
    """Read bounded metadata, tensor headers, and per-rank extra state."""
    metadata_path = CHECKPOINT / ".metadata"
    if metadata_path.stat().st_size > 2 * 1024 * 1024:
        raise ValueError("Unexpected metadata size")
    metadata = FileSystemReader(CHECKPOINT).load_metadata()
    tensor_names = sorted(metadata.state_dict_metadata)
    byte_values = {}
    for index, storage in metadata.storage_data.items():
        if not storage.relative_path.endswith(".bytes"):
            continue
        path = (CHECKPOINT / storage.relative_path).resolve()
        if path.parent != CHECKPOINT or path.stat().st_size > 2 * 1024 * 1024:
            raise ValueError("Unexpected byte storage path or size")
        with path.open("rb") as stream:
            stream.seek(storage.offset)
            payload = stream.read(storage.length)
        if len(payload) != storage.length:
            raise ValueError("Truncated byte metadata")
        byte_values[index.fqn] = summarize(pickle.loads(payload))
    extra_states = []
    tensor_headers = []
    for rank in range(8):
        path = CHECKPOINT / "extra_state" / f"extra_state_rank_{rank}.pt"
        if path.stat().st_size > 2 * 1024 * 1024:
            raise ValueError("Unexpected extra state size")
        # The checkpoint is generated by this task; never use this on untrusted files.
        state = torch.load(path, map_location="cpu", weights_only=False)
        extra_states.append({"rank": rank, "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                             "state": summarize(state)})
        tensor_path = CHECKPOINT / f"_rank{rank}_.safetensors"
        with tensor_path.open("rb") as stream:
            header_size = struct.unpack("<Q", stream.read(8))[0]
            if header_size > 4 * 1024 * 1024:
                raise ValueError("Unexpected safetensors header size")
            header = json.loads(stream.read(header_size))
        entries = {key: value for key, value in header.items() if key != "__metadata__"}
        tensor_headers.append({"rank": rank, "file_size": tensor_path.stat().st_size,
                               "header_size": header_size, "tensor_count": len(entries),
                               "dtype_counts": dict(Counter(value["dtype"] for value in entries.values()))})
    result = {
        "scope": "CPU metadata inspection only; no model tensor data read, no restore or precision verdict",
        "import_path": hyper_parallel.__file__,
        "metadata_sha256": hashlib.sha256(metadata_path.read_bytes()).hexdigest(),
        "metadata_entry_count": len(tensor_names),
        "metadata_names": tensor_names,
        "byte_values": byte_values,
        "extra_states": extra_states,
        "tensor_headers": tensor_headers,
    }
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
